/** میانگین اسکن از لاگ مسابقات */
function scanAvg(S) {
  const L = (S.dec || []).filter(x => typeof x.scan === 'number');
  if (!L.length) return null;
  const avg = L.reduce((a, x) => a + x.scan, 0) / L.length;
  return {
    n: L.length,
    avg: Math.round(avg * 10) / 10,
    /* مرجع: متوسط ۲، خوب ۵، حرفه‌ای ۸ */
    tier: avg >= 8 ? 4 : avg >= 5 ? 3 : avg >= 3 ? 2 : 1,
    last5: L.slice(-5).map(x => x.scan)
  };
}

/** دقت پاس از خوداظهاری بعد از مسابقه */
function passAcc(S) {
  const L = (S.dec || []).filter(x => typeof x.good === 'number' && typeof x.bad === 'number');
  if (!L.length) return null;
  const good = L.reduce((a, x) => a + x.good, 0);
  const bad = L.reduce((a, x) => a + x.bad, 0);
  const tot = good + bad;
  return {
    n: L.length, good, bad,
    pc: tot ? Math.round(good / tot * 100) : 0,
    trend: L.length >= 4
      ? Math.round((L.slice(-2).reduce((a, x) => a + x.good / Math.max(1, x.good + x.bad), 0) / 2 -
                    L.slice(0, 2).reduce((a, x) => a + x.good / Math.max(1, x.good + x.bad), 0) / 2) * 100)
      : null
  };
}

/** امتیاز کل تصمیم‌گیری */
function decScore(S) {
  const sc = scanAvg(S), pa = passAcc(S);
  const done = (S.decDrill || []).length;
  const drillPc = Math.round(done / DDRILL.length * 100);
  const scanPc = sc ? Math.min(100, Math.round(sc.avg / 8 * 100)) : 0;
  const accPc = pa ? pa.pc : 0;
  const all = Math.round(drillPc * 0.3 + scanPc * 0.35 + accPc * 0.35);
  const ranks = ['نادیده', 'آگاه', 'بیننده', 'خواننده', 'سازنده'];
  return {
    all, drillPc, scanPc, accPc,
    scan: sc, acc: pa,
    rank: ranks[Math.min(4, Math.floor(all / 20))]
  };
}

/** تمرین امروز — چرخشی بین سه جزء با اولویت ضعیف‌ترین */
function decToday(S) {
  const done = S.decDrill || [];
  const sc = decScore(S);
  /* ضعیف‌ترین جزء را هدف بگیر */
  let want = 'scan';
  if (sc.scanPc >= 60 && sc.accPc < 60) want = 'option';
  if (sc.scanPc >= 60 && sc.accPc >= 60) want = 'speed';
  const pool = DDRILL.filter(d => d[1] === want);
  const todo = pool.filter(d => !done.includes(d[0]));
  const list = todo.length ? todo : pool;
  return list[Math.floor(Date.now() / 864e5) % list.length];
}

