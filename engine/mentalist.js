/** پیشرفت هر ستون */
function pillarScore(S, key) {
  const p = PILLARS.find(x => x[0] === key);
  if (!p) return { pc: 0, done: 0, total: 0 };
  const done = ((S.ment && S.ment[key]) || []).length;
  return { pc: Math.round(done / p[2].length * 100), done, total: p[2].length };
}

/** دقت استنتاج: چند حدس زدی و چند تا درست بود */
function readAccuracy(S) {
  const log = (S.ment && S.ment.reads) || [];
  if (!log.length) return { n: 0, hit: 0, pc: 0 };
  const hit = log.filter(r => r.ok).length;
  return { n: log.length, hit, pc: Math.round(hit / log.length * 100) };
}

/** امتیاز کلی و رتبه */
function mentScore(S) {
  const cols = PILLARS.map(p => pillarScore(S, p[0]).pc);
  const base = cols.reduce((a, b) => a + b, 0) / cols.length;
  const field = Math.min(100, ((S.ment && S.ment.field) || []).length / FIELD.length * 100);
  const acc = readAccuracy(S);
  /* دقت فقط وقتی حساب می‌شود که حداقل ۵ حدس ثبت شده باشد */
  const accPart = acc.n >= 5 ? acc.pc : 0;
  const all = Math.round(base * 0.5 + field * 0.3 + accPart * 0.2);
  const ranks = ['ناظر', 'دقیق', 'تیزبین', 'خواننده', 'منتالیست'];
  return {
    cols, base: Math.round(base), field: Math.round(field), acc,
    all, rank: ranks[Math.min(4, Math.floor(all / 20))]
  };
}

/** تمرین میدانی امروز — چرخشی */
function fieldToday(S) {
  const done = (S.ment && S.ment.field) || [];
  const todo = FIELD.filter(f => !done.includes(f[0]));
  if (!todo.length) return null;
  return todo[Math.floor(Date.now() / 864e5) % todo.length];
}

