/** سطح یک مهارت بر اساس عدد سنجیده‌شده */
function skTier(key, v) {
  const s = SK_MAP[key];
  if (!s || typeof v !== 'number' || isNaN(v)) return 0;
  const marks = s[3], lower = s[4] === 1;
  let t = 0;
  for (let i = 0; i < marks.length; i++)
    if (lower ? v <= marks[i] : v >= marks[i]) t = i + 1;
  return t;
}

/** پروفایل کامل بازیکن */
function player(S) {
  const log = S.fb || {};
  const tiers = {};
  SKILL.forEach(s => { tiers[s[0]] = skTier(s[0], log[s[0]]); });
  const vals = SKILL.map(s => tiers[s[0]]);
  const tested = vals.filter(v => v > 0).length;
  const overall = Math.round(vals.reduce((a, b) => a + b, 0) / (SKILL.length * 5) * 100);

  /* نقاط قوت و ضعف */
  const ranked = SKILL.map(s => ({ k: s[0], n: s[1], t: tiers[s[0]] }))
                      .sort((a, b) => b.t - a.t);
  const strong = ranked.filter(x => x.t >= 3).slice(0, 3);
  const weak = ranked.filter(x => x.t > 0).slice(-3).reverse();
  const untested = SKILL.filter(s => !tiers[s[0]]).map(s => s[1]);

  return { tiers, overall, tested, strong, weak, untested, total: SKILL.length };
}

/**
 * تناسب با پست.
 * مهارت‌های اختصاصی آن پست وزن دوبرابر دارند، چون همان‌ها پست را تعریف می‌کنند.
 * پستی که مهارت اختصاصی‌اش سنجیده نشده، تناسبش پایین می‌ماند —
 * وگرنه دروازه‌بان فقط با سرعت و استقامت بالا می‌آمد.
 */
function posFit(S, code) {
  const p = POS.find(x => x[0] === code);
  if (!p) return 0;
  const pl = player(S);
  const gen = SKILL.filter(s => s[5].includes('all'));
  const spec = SKILL.filter(s => s[5].includes(code));
  if (!spec.length) {
    /* پستی بدون مهارت اختصاصی در فهرست: فقط عمومی، با سقف ۵۰٪ */
    const sum = gen.reduce((a, s) => a + pl.tiers[s[0]], 0);
    return Math.round(sum / (gen.length * 5) * 50);
  }
  const gSum = gen.reduce((a, s) => a + pl.tiers[s[0]], 0);
  const sSum = spec.reduce((a, s) => a + pl.tiers[s[0]], 0);
  const gMax = gen.length * 5, sMax = spec.length * 5;
  /* وزن: عمومی ۱، اختصاصی ۲ */
  return Math.round((gSum + sSum * 2) / (gMax + sMax * 2) * 100);
}

/** بهترین پست بر اساس داده، نه سلیقه */
function bestPos(S) {
  return POS.map(p => ({ code: p[0], name: p[1], fit: posFit(S, p[0]) }))
            .sort((a, b) => b.fit - a.fit);
}

/** آمار مسابقات */
function matchStats(S) {
  const ms = (S.ms || []).filter(m => m && typeof m.min === 'number');
  if (!ms.length) return null;
  const n = ms.length;
  const sum = k => ms.reduce((a, m) => a + (+m[k] || 0), 0);
  const mins = sum('min');
  return {
    n, mins,
    goals: sum('g'), assists: sum('a'),
    rate: Math.round(ms.reduce((a, m) => a + (+m.rate || 0), 0) / n * 10) / 10,
    per90g: mins ? Math.round(sum('g') / mins * 90 * 100) / 100 : 0,
    per90a: mins ? Math.round(sum('a') / mins * 90 * 100) / 100 : 0,
    last5: ms.slice(-5).map(m => +m.rate || 0)
  };
}

/** مرحلهٔ فعلی مسیر */
function pathStage(S, age) {
  const pl = player(S);
  const a = age || 14;
  /* مرحله بر پایهٔ سن، ولی پیشرفت بر پایهٔ معیارها */
  const stage = PATH.find(p => p[2] >= a) || PATH[PATH.length - 1];
  return { stage, overall: pl.overall };
}

/** تمرین پیشنهادی امروز: بر اساس ضعف واقعی */
function trainToday(S) {
  const pl = player(S);
  if (pl.tested < 3) return TRAIN[0];        /* اول بسنج */
  const w = pl.weak[0];
  if (!w) return TRAIN[0];
  /* مهارت ضعیف را به بلوک تمرینی نگاشت کن */
  const map = {
    juggle: 'tech', weak: 'tech', first: 'tech', shortp: 'tech',
    longp: 'tech', cone: 'tech',
    sprint: 'speed', agil: 'speed', cooper: 'speed', vjump: 'speed',
    finish: 'finish', oneone: 'finish', head: 'finish', cross: 'finish',
    scan: 'game'
  };
  return TRAIN.find(t => t[0] === (map[w.k] || 'tech')) || TRAIN[0];
}

