/* برنامهٔ هفتگی مطالعه بر اساس ضریب و سختی */
function studyPlan(S){
  const done=S.stLog||{};
  return SUBJ.map(s=>{
    const w=s[3]*DIFF_W[s[4]];
    const minsWeek=Math.round(w*22);           // دقیقهٔ پیشنهادی در هفته
    const wk=weekKey();
    const got=(done[wk]&&done[wk][s[0]])||0;
    return {k:s[0],t:s[1],ic:s[2],coef:s[3],diff:s[4],d:s[5],
            target:minsWeek,got,pc:Math.min(100,Math.round(got/minsWeek*100))};
  }).sort((a,b)=>b.target-a.target);
}
function weekKey(){const d=new Date();const on=new Date(d.getFullYear(),0,1);
  return d.getFullYear()+'-w'+Math.ceil(((d-on)/864e5+on.getDay()+1)/7)}

/* میانگین و تحلیل نمرات */
function gpa(S){
  const g=S.grades||{};
  let sum=0,wsum=0,list=[];
  SUBJ.forEach(s=>{
    const arr=g[s[0]]||[];
    if(!arr.length)return;
    const av=arr.reduce((a,b)=>a+b.v,0)/arr.length;
    list.push({k:s[0],t:s[1],ic:s[2],av:+av.toFixed(2),n:arr.length,coef:s[3],
      trend:arr.length>=2?+(arr[arr.length-1].v-arr[arr.length-2].v).toFixed(1):0});
    sum+=av*s[3];wsum+=s[3];
  });
  return {avg:wsum?+(sum/wsum).toFixed(2):0, list:list.sort((a,b)=>a.av-b.av)};
}

/* توصیهٔ رشته بر اساس نمرات واقعی */
function streamAdvice(S){
  const G=gpa(S), m={};G.list.forEach(x=>m[x.k]=x.av);
  return STREAMS.map(st=>{
    const ks=Object.keys(st.need);
    let score=0,n=0,gaps=[];
    ks.forEach(k=>{
      if(m[k]!==undefined){n++;
        const r=Math.min(1.15,m[k]/st.need[k]);score+=r;
        if(m[k]<st.need[k])gaps.push(`${(SUBJ.find(s=>s[0]===k)||[])[1]}: ${fa(m[k])} → نیاز ${fa(st.need[k])}`);
      }});
    return {...st, fit:n?Math.round(score/n*100):null, gaps};
  }).sort((a,b)=>(b.fit||0)-(a.fit||0));
}

