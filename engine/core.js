/* ================= ADAPTIVE ENGINE ================= */
function adapt(hist){
  // hist: [{d, rate}] نرخ تکمیل روزانه
  const out=[];
  if(!hist.length) return out;
  const last7=hist.slice(-7), avg=last7.reduce((a,x)=>a+x.rate,0)/last7.length;
  if(avg<0.45) out.push(['بار برنامه زیاد است','نرخ تکمیل زیر ۴۵٪. دو بلوک کم‌اولویت حذف شود تا ریتم برگردد.']);
  else if(avg>0.9) out.push(['ظرفیت آزاد داری','نرخ تکمیل بالای ۹۰٪. یک بلوک مهارت یا تمرین اضافه کن.']);
  else out.push(['تعادل مناسب','نرخ تکمیل در محدودهٔ بهینه است. تغییری لازم نیست.']);
  return out;
}

