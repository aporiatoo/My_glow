/* پیشنهاد اضافه‌بار تدریجی: اگر در آخرین جلسه همهٔ ست‌ها در سقف تکرار بود، وزنه بالا برود */
function overload(hist,bw){
  if(!hist||!hist.length) return null;
  const last = hist[hist.length-1];
  if(bw){ // وزن بدن: اضافه‌بار از راه تکرار و ست
    if(last.r >= 20) return {w:last.w, r:12, s:(last.s||3)+1, why:'به ۲۰ تکرار رسیدی — یک ست اضافه کن و تکرار به ۱۲ برگردد'};
    return {w:last.w, r:last.r+1, s:last.s||3, why:'یک تکرار بیشتر از جلسهٔ قبل'};
  }
  if(last.r >= 12) return {w: Math.round((last.w*1.05)*2)/2, r: 8, why:'سقف تکرار زده شد — وزنه ۵٪ بالا، تکرار به ۸ برگردد'};
  if(last.r >= 8)  return {w: last.w, r: last.r+1, why:'همان وزنه، یک تکرار بیشتر'};
  return {w: last.w, r: Math.max(6,last.r), why:'تثبیت — همان وزنه تا رسیدن به ۸ تکرار'};
}

