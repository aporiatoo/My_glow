/* ================= PATTERN DETECTION ================= */
function patterns(S){
  const out=[];
  // الگوی زمانی لغزش‌ها
  if(S.logs&&S.logs.length>=3){
    const hrs=S.logs.map(l=>new Date(l.d).getHours());
    const late=hrs.filter(h=>h>=21||h<=3).length;
    if(late/hrs.length>=0.6) out.push(['زمان بحرانی تو شب است',
      Math.round(late/hrs.length*100)+'٪ لغزش‌ها بین ۲۱ تا ۰۳ رخ داده. راه‌حل ساختاری: گوشی بیرون اتاق، نه اراده.']);
    const dys=S.logs.map(l=>new Date(l.d).getDay());
    const cnt={};dys.forEach(d=>cnt[d]=(cnt[d]||0)+1);
    const top=Object.entries(cnt).sort((a,b)=>b[1]-a[1])[0];
    if(top&&top[1]>=2&&top[1]/dys.length>=0.4) out.push(['روز پرخطر: '+JW[top[0]],
      'بیشترین لغزش‌ها در این روز. برای این روز برنامهٔ فشرده‌تر و بیرون از خانه بچین.']);
  }
  // همبستگی خواب و عملکرد
  if(S.hist&&S.hist.length>=7){
    const r=S.hist.slice(-14);
    const hi=r.filter(x=>x.rate>=0.7).length, lo=r.filter(x=>x.rate<0.4).length;
    if(lo>hi) out.push(['روند نزولی','در ۱۴ روز اخیر روزهای ضعیف بیشتر از روزهای قوی بوده. برنامه را سبک کن تا ریتم برگردد — این شکست نیست، تنظیم است.']);
    else if(hi>=r.length*0.7) out.push(['روند صعودی پایدار','بیش از ۷۰٪ روزها بالای ۷۰٪ تکمیل. ظرفیت اضافه کردن یک هدف جدید را داری.']);
  }
  // همبستگی حال و تمرین
  if(S.jr&&S.jr.length>=5){
    const av=S.jr.slice(-10).reduce((a,x)=>a+ +x.m,0)/Math.min(10,S.jr.length);
    if(av<=2.5) out.push(['حال عمومی پایین','میانگین حال ۱۰ روز اخیر پایین است. اولویت: خواب، نور طبیعی صبح، و ورزش هوازی. اگر بیش از دو هفته ادامه داشت با کسی حرف بزن.']);
    else if(av>=4) out.push(['حال عمومی خوب','میانگین حال بالاست. بهترین زمان برای شروع یک عادت سخت جدید.']);
  }
  if(!out.length) out.push(['داده کافی نیست','برای تشخیص الگو حداقل یک هفته ثبت منظم لازم است. ادامه بده.']);
  return out;
}

