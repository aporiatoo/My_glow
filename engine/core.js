/* ---------- Jalali date ---------- */
function toJalali(gy, gm, gd) {
  const g_d_m = [0,31,59,90,120,151,181,212,243,273,304,334];
  let jy = gy <= 1600 ? 0 : 979;
  gy -= gy <= 1600 ? 621 : 1600;
  const gy2 = gm > 2 ? gy + 1 : gy;
  let days = 365*gy + ((gy2+3)/4|0) - ((gy2+99)/100|0) + ((gy2+399)/400|0) - 80 + gd + g_d_m[gm-1];
  jy += 33*((days/12053)|0); days %= 12053;
  jy += 4*((days/1461)|0); days %= 1461;
  if (days > 365) { jy += ((days-1)/365)|0; days = (days-1)%365; }
  const jm = days < 186 ? 1 + ((days/31)|0) : 7 + (((days-186)/30)|0);
  const jd = 1 + (days < 186 ? days%31 : (days-186)%30);
  return [jy, jm, jd];
}
