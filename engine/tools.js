/** ساخت لاین‌آپ با نام بازیکنان */
function lineup(kind, form, names) {
  const src = kind === 'futsal' ? FORM5 : FORM11;
  const f = src[form] || Object.values(src)[0];
  return f.map((p, i) => ({
    x: p[0], y: p[1], pos: p[2],
    name: (names && names[i]) || '',
    n: i + 1
  }));
}

