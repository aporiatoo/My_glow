/* ============================================================
   ۵. ماشین‌حساب وزن و ترکیب بدن
   ============================================================ */
function bodyCalc(h, w, age) {
  if (!h || !w) return null;
  const m = h / 100;
  const bmi = w / (m * m);
  /* در نوجوانی BMI مطلق گمراه‌کننده است — بازهٔ سنی مهم است */
  const low = 17.5, high = 23;
  return {
    bmi: Math.round(bmi * 10) / 10,
    state: bmi < low ? 'کم' : bmi > high ? 'بالا' : 'طبیعی',
    idealMin: Math.round(low * m * m),
    idealMax: Math.round(high * m * m),
    /* پروتئین: ۱.۶ تا ۲ گرم به ازای کیلو برای ورزشکار نوجوان */
    protMin: Math.round(w * 1.6),
    protMax: Math.round(w * 2)
  };
}

/* ============================================================
   ۶. شمارش معکوس — رویدادهای مهم
   ============================================================ */
function countdown(dateStr) {
  if (!dateStr) return null;
  const t = new Date(dateStr) - Date.now();
  const d = Math.ceil(t / 864e5);
  return { days: d, past: d < 0, today: d === 0, soon: d > 0 && d <= 7 };
}

/* ============================================================
   ۷. تبدیل واحد ورزشی
   ============================================================ */
function convert(v, from) {
  const n = +v;
  if (isNaN(n)) return null;
  const C = {
    'km/h→m/s': n / 3.6,
    'm/s→km/h': n * 3.6,
    'sprint20': n > 0 ? Math.round(20 / n * 3.6 * 10) / 10 : 0,   /* ثانیه → km/h */
    'cooper→vo2': Math.round(((n - 504.9) / 44.73) * 10) / 10,     /* متر → VO2max */
    'cm→ft': Math.floor(n / 30.48) + "'" + Math.round((n / 2.54) % 12) + '"'
  };
  return C[from] !== undefined ? C[from] : null;
}

