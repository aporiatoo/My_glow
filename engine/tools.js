function msgFill(tpl, vars) {
  return String(tpl).replace(/\{(\w+)\}/g, (m, k) =>
    (vars && vars[k] !== undefined && vars[k] !== '') ? vars[k] : '___');
}

/* ============================================================
   ۳. ماشین‌حساب معدل — چه نمره‌ای لازم دارم
   ============================================================ */
/**
 * @param cur  آرایهٔ {score, weight} نمرات فعلی
 * @param goal معدل هدف
 * @param left آرایهٔ {name, weight} درس‌های باقی‌مانده
 */
function gpaNeed(cur, goal, left) {
  const cw = cur.reduce((a, x) => a + (x.weight || 1), 0);
  const cs = cur.reduce((a, x) => a + (x.score || 0) * (x.weight || 1), 0);
  const lw = left.reduce((a, x) => a + (x.weight || 1), 0);
  if (!lw) return { possible: cw ? cs / cw >= goal : false, need: null, cur: cw ? cs / cw : 0 };
  const need = (goal * (cw + lw) - cs) / lw;
  return {
    cur: cw ? Math.round(cs / cw * 100) / 100 : 0,
    need: Math.round(need * 100) / 100,
    possible: need <= 20,
    comfortable: need <= 18,
    impossible: need > 20
  };
}

