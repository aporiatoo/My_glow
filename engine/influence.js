/** امتیاز دفاعی: چند تاکتیک را می‌شناسی */
function defScore(S) {
  const known = (S.inf && S.inf.known) || [];
  const byLevel = { 3: 0, 2: 0, 1: 0 };
  TACTIC.forEach(t => { if (known.includes(t[0])) byLevel[SEVER[t[2]]]++; });
  const total = TACTIC.filter(t => SEVER[t[2]] === 3).length * 3 +
                TACTIC.filter(t => SEVER[t[2]] === 2).length * 2 +
                TACTIC.filter(t => SEVER[t[2]] === 1).length;
  const got = byLevel[3] * 3 + byLevel[2] * 2 + byLevel[1];
  return { pc: Math.round(got / total * 100), known: known.length, total: TACTIC.length };
}

/** امتیاز مذاکره */
function negoScore(S) {
  const done = (S.inf && S.inf.nego) || [];
  return { pc: Math.round(done.length / NEGO.length * 100), done: done.length, total: NEGO.length };
}

/** دقت در سناریوها */
function drillScore(S) {
  const log = (S.inf && S.inf.drill) || {};
  const ids = Object.keys(log);
  if (!ids.length) return { pc: 0, done: 0, correct: 0, total: SCEN.length };
  const correct = ids.filter(k => log[k] === true).length;
  return {
    pc: Math.round(correct / SCEN.length * 100),
    done: ids.length, correct, total: SCEN.length
  };
}

/** امتیاز کلی نفوذ */
function infScore(S) {
  const d = defScore(S), n = negoScore(S), k = drillScore(S);
  const all = Math.round((d.pc + n.pc + k.pc) / 3);
  const ranks = ['ناآگاه', 'هوشیار', 'مقاوم', 'ماهر', 'استاد'];
  return { def: d, nego: n, drill: k, all, rank: ranks[Math.min(4, Math.floor(all / 20))] };
}

/** سناریوی بعدی که هنوز درست جواب داده نشده */
function nextScen(S) {
  const log = (S.inf && S.inf.drill) || {};
  const todo = SCEN.filter(s => log[s.id] !== true);
  if (!todo.length) return null;
  return todo[Math.floor(Date.now() / 864e5) % todo.length];
}

