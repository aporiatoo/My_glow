/* انرژی تخمینی بدن در طول روز (۰–۱۰۰) بر اساس ریتم شبانه‌روزی نوجوان */
function energyAt(m){
  const c=[[0,8],[240,5],[300,35],[360,62],[420,78],[540,92],[660,88],[780,70],
           [840,62],[900,80],[1020,85],[1110,70],[1200,52],[1260,34],[1320,18],[1439,10]];
  for(let i=0;i<c.length-1;i++){
    if(m>=c[i][0]&&m<=c[i+1][0]){
      const f=(m-c[i][0])/(c[i+1][0]-c[i][0]);
      return Math.round(c[i][1]+(c[i+1][1]-c[i][1])*f);
    }
  }
  return 50;
}
