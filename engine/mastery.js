const TIERS = ['تازه‌کار', 'آموزنده', 'ماهر', 'پیشرفته', 'استاد'];

/**
 * سطح یک مهارت فوتبال بر اساس عدد واقعی.
 * برای دریبل که «کمتر بهتر» است، منطق معکوس می‌شود.
 */
function fskillTier(key, value) {
  const s = FSKILL.find(x => x[0] === key);
  if (!s || typeof value !== 'number') return 0;
  const marks = s[3];
  const lower = key === 'dribble';
  let t = 0;
  for (let i = 0; i < marks.length; i++) {
    if (lower ? value <= marks[i] : value >= marks[i]) t = i + 1;
  }
  return t;
}

/** پیشرفت کلی فوتبال: میانگین سطوح، صفر تا صد */
function footballScore(S) {
  const log = S.fsk || {};
  const tiers = FSKILL.map(s => fskillTier(s[0], log[s[0]]));
  const sum = tiers.reduce((a, b) => a + b, 0);
  return {
    pc: Math.round(sum / (FSKILL.length * 5) * 100),
    tiers,
    tested: tiers.filter(t => t > 0).length,
    weakest: FSKILL[tiers.indexOf(Math.min(...tiers))]
  };
}

/**
 * تسلط ذهنی: بر پایهٔ تمرین‌های انجام‌شده، نه زمان سپری‌شده.
 * هر بخش سهم مساوی دارد تا یک حوزه بقیه را نپوشاند.
 */
function mindScore(S) {
  const m = S.mind2 || {};
  const parts = [
    { k: 'micro', n: MICRO.length,     done: (m.micro || []).length },
    { k: 'tells', n: TELLS.length,     done: (m.tells || []).length },
    { k: 'infl',  n: INFLUENCE.length, done: (m.infl || []).length },
    { k: 'fall',  n: FALLACY.length,   done: (m.fall || []).length },
    { k: 'model', n: MODELS.length,    done: (m.model || []).length }
  ];
  const pc = Math.round(
    parts.reduce((a, p) => a + Math.min(1, p.done / p.n), 0) / parts.length * 100);
  return { pc, parts, reps: m.reps || 0 };
}

/** تسلط ظاهری: از داده‌های واقعی اپ، نه خوداظهاری */
function lookScore(S) {
  let n = 0, tot = 0;
  const add = (ok, w) => { tot += w; if (ok) n += w; };

  const d30 = 30, now = Date.now();
  const recent = (arr, days) => (arr || []).filter(x => {
    const dt = x && (x.d || x.date);
    return dt && (now - new Date(dt)) / 864e5 <= days;
  }).length;

  add((S.streak && S.streak.clean) >= 7, 1);                 // ثبات کلی
  add(recent(S.photos, 45) > 0, 1);                          // عکس پیشرفت
  add((S.hts || []).length >= 2, 1);                         // پایش قد
  add(recent(S.jr, 7) >= 3, 1);                              // خواب و ثبات
  const sl = S.sleepLog || {};
  const nights = Object.keys(sl).slice(-7);
  add(nights.length >= 3 &&
      nights.reduce((a, k) => a + (+sl[k] || 0), 0) / nights.length >= 8, 2);
  add((S.prot && Object.keys(S.prot).length > 0), 1);        // پروتکل‌ها
  add(recent(S.wo, d30) >= 8, 2);                            // تمرین منظم

  return { pc: Math.round(n / tot * 100) };
}

/** نمرهٔ کل — میانگین سه حوزه */
function masteryScore(S) {
  const mind = mindScore(S).pc;
  const body = footballScore(S).pc;
  const look = lookScore(S).pc;
  const all = Math.round((mind + body + look) / 3);
  return {
    mind, body, look, all,
    tier: TIERS[Math.min(4, Math.floor(all / 20))],
    weakest: mind <= body && mind <= look ? 'mind'
           : body <= look ? 'body' : 'look'
  };
}

/** تمرین ذهنی امروز — چرخشی تا همه پوشش داده شوند */
function mindToday(S) {
  const day = Math.floor(Date.now() / 864e5);
  const pool = [
    { t: 'micro', items: MICRO,     title: 'ریزحالت چهره' },
    { t: 'tells', items: TELLS,     title: 'نشانهٔ ناهماهنگی' },
    { t: 'infl',  items: INFLUENCE, title: 'اصل نفوذ' },
    { t: 'fall',  items: FALLACY,   title: 'مغالطه' },
    { t: 'model', items: MODELS,    title: 'مدل ذهنی' }
  ];
  const p = pool[day % pool.length];
  const item = p.items[Math.floor(day / pool.length) % p.items.length];
  return { type: p.t, title: p.title, item };
}

